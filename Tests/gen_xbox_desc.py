#!/usr/bin/env python3
"""Generate Shared/xpad_xbox_desc.c from the captured descriptor.

The bytes come only from the .bin (docs/research/xbox_series_ble_0b13_
descriptor.bin). The commented decode next to it supplies one comment per
HID item; it is used only if its bytes are exactly the .bin's, item for
item, so a comment can never sit next to the wrong bytes.

    gen_xbox_desc.py DESCRIPTOR.bin COMMENTED.c [OUT.c]   (default: stdout)

Run by `make -C Tests desc` (rewrites the file) and checked by
`make -C Tests` (regenerates into the build directory and diffs).
"""
import re
import sys

EXPECTED_LEN = 283
EXPECTED_CRC = 0x931D

HEADER = """\
/*
 * The HID report descriptor XPadMac publishes: the real one of an Xbox
 * Wireless Controller (Series X|S, 045E:0B13) on Bluetooth LE firmware,
 * {n} bytes, CRC-16/ARC 0x{crc:04X} (the "unified" descriptor xpadneo
 * documents). Apple's XboxOneHIDServicePlugin reads its elements to pick
 * the report layout (Brake + Accelerator = Android layout, no AC Back = View
 * in the button field, Record = Share present), so it is used byte for byte.
 *
 *   Report 1, input, 16 bytes + ID: X Y Z Rz u16, Brake Accelerator 10 bits,
 *            hat 4 bits, buttons 1..15, Consumer Record (Share).
 *   Report 3, output, 8 bytes + ID: enable nibble, 4 magnitudes 0..100,
 *            duration (10 ms), start delay, loop count.
 *
 * GENERATED by Tests/gen_xbox_desc.py from
 * docs/research/xbox_series_ble_0b13_descriptor.bin (comments from
 * docs/research/xbox_series_ble_0b13_descriptor_commented.c). Do not edit:
 * run `make -C Tests desc`.
 *
 * SPDX-License-Identifier: GPL-3.0-or-later
 */
#include "xpad.h"

const uint8_t xpad_xbox_desc[XPAD_XBOX_DESC_LEN] = {{
"""

FOOTER = "};\n"


def crc16_arc(data):
    crc = 0
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = (crc >> 1) ^ 0xA001 if crc & 1 else crc >> 1
    return crc


def hid_items(data):
    """Split a report descriptor into its items (short items only, plus the
    long-item form for completeness)."""
    i = 0
    while i < len(data):
        prefix = data[i]
        if prefix == 0xFE:                       # long item
            if i + 2 >= len(data):
                raise ValueError("long item cut short at %d" % i)
            n = 3 + data[i + 1]
        else:
            n = 1 + (0, 1, 2, 4)[prefix & 0x03]
        if i + n > len(data):
            raise ValueError("item at %d runs past the end" % i)
        yield data[i:i + n]
        i += n


LINE = re.compile(r"^\s*((?:0x[0-9A-Fa-f]{2},\s*)+)//\s?(.*)$")


def commented_lines(path):
    """(bytes, comment) for every byte line of the commented decode."""
    out = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = LINE.match(line)
            if m:
                bs = bytes(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", m.group(1)))
                out.append((bs, m.group(2).rstrip()))
    return out


def main(argv):
    if len(argv) not in (3, 4):
        sys.stderr.write(__doc__)
        return 2
    with open(argv[1], "rb") as f:
        data = f.read()
    if len(data) != EXPECTED_LEN or crc16_arc(data) != EXPECTED_CRC:
        sys.stderr.write("%s: %d bytes, CRC 0x%04X; expected %d bytes, CRC 0x%04X\n"
                         % (argv[1], len(data), crc16_arc(data), EXPECTED_LEN, EXPECTED_CRC))
        return 1

    items = list(hid_items(data))
    notes = commented_lines(argv[2])
    if [bs for bs, _ in notes] != items:
        sys.stderr.write("%s: its bytes are not the .bin's, item for item; not using its comments\n" % argv[2])
        notes = [(it, "") for it in items]

    width = max(len(", ".join("0x%02X" % b for b in it)) + 1 for it in items)
    body = []
    for it, note in notes:
        hexes = ", ".join("0x%02X" % b for b in it) + ","
        body.append(("    %-*s  /* %s */" % (width, hexes, note)) if note else "    " + hexes)
    text = HEADER.format(n=len(data), crc=crc16_arc(data)) + "\n".join(body) + "\n" + FOOTER

    if len(argv) == 4:
        with open(argv[3], "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
